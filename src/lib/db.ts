/**
 * Backfill any missing label + 3D fields in saved grid configs. Called once
 * on app boot so older rows that predate the per-grid label customization
 * or the elevation/height split still render correctly. Only writes when
 * a field is undefined (or migrates a legacy `altitude` value to the new
 * `height` field), so it's safe to call on every boot.
 *
 * Migration history:
 * - Pre-label-customization: added labelStart, labelDirection, labelPrefix,
 *   labelSize, labelColor, labelAltitude.
 * - Pre-3D-split: `altitude` meant "extrusion height" (top above base 0).
 *   Now split into `elevation` (base) and `height` (extrusion top - base).
 *   Any legacy row with a numeric `altitude` field gets:
 *     elevation = 0, height = old altitude.
 */
export async function backfillGridConfig(): Promise<void> {
  const defaults: Partial<GridConfig> = {
    labelStart: 1,
    labelDirection: 'x',
    labelPrefix: '',
    labelSize: 11,
    labelColor: '#000000',
    labelAltitude: 0,
    elevation: 0,
    height: 0,
    // Old rows predate the per-grid display unit. Stamping 'm' is safe —
    // their stored xSize/ySize were already meters.
    unit: 'm',
    // Pre-racking grids are implicitly single-level. Stamping `1` /
    // `1.5` here means existing grids keep their current 2D / single-
    // extrusion behaviour and the level-aware code path is a no-op
    // until the user upgrades a grid to a multi-level rack.
    levels: 1,
    levelHeight: 1.5,
    // Pre-gap grids have no horizontal or vertical seams beyond the
    // legacy 3% fractional inset. Stamping `0` keeps them bit-identical.
    cellGap: 0,
    levelGap: 0,
  }
  await db.grids.toCollection().modify((grid) => {
    const cfg = grid.config
    if (!cfg) return
    let dirty = false
    // Legacy migration: if the row has the old `altitude` field (and the new
    // `height` field is not yet defined), move it across. Use bracket access
    // to keep the cast minimal and to read the legacy key.
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const legacyAny = cfg as any
    if (
      typeof legacyAny.altitude === 'number' &&
      legacyAny.height === undefined
    ) {
      legacyAny.height = legacyAny.altitude
      legacyAny.elevation = 0
      delete legacyAny.altitude
      dirty = true
    }
    for (const [k, v] of Object.entries(defaults)) {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      if ((cfg as any)[k] === undefined) {
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        ;(cfg as any)[k] = v
        dirty = true
      }
    }
    if (dirty) grid.updatedAt = new Date()
  })
}

/**
 * Backfill image rows saved with the pre-bbox schema (center `position` +
 * `width` / `height` meters) into the new corner-pair schema
 * (`start` / `current`). The image rendering pipeline was reworked from
 * an HTML overlay (sized in meters around a center) to a Mapbox raster
 * source (defined by four lng/lat corners), so legacy rows have to be
 * translated before they can be drawn.
 *
 * Old rows that already have `start` + `current` are left alone, so this
 * is safe to run on every boot. Rows that lack both schemas get deleted
 * — they can't be rendered at all and would crash the overlay otherwise.
 */
export async function backfillImageConfig(): Promise<void> {
  const EARTH_RADIUS = 6378137
  await db.images.toCollection().modify((row) => {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const r = row as any
    let dirty = false
    // Stamp `config.elevation` on rows that predate the field so the
    // floor-plan layer always reads a valid altitude instead of NaN.
    // Safe to run on every boot.
    if (r.config && typeof r.config === 'object') {
      if (r.config.elevation === undefined) {
        r.config.elevation = 0
        dirty = true
      }
    }
    if (Array.isArray(r.start) && Array.isArray(r.current)) {
      if (dirty) row.updatedAt = new Date()
      return
    }
    const pos = r.position
    const width = r.width
    const height = r.height
    if (
      !Array.isArray(pos) ||
      typeof pos[0] !== 'number' ||
      typeof pos[1] !== 'number' ||
      typeof width !== 'number' ||
      typeof height !== 'number'
    ) {
      // Row has neither schema — mark it unrenderable. Deleting from
      // inside .modify isn't supported; the overlay's null-guard will
      // simply skip it on the next render.
      if (dirty) row.updatedAt = new Date()
      return
    }
    const halfDLat = ((height / 2) / EARTH_RADIUS) * (180 / Math.PI)
    const cosLat = Math.cos((pos[1] * Math.PI) / 180)
    const halfDLng =
      cosLat < 1e-9
        ? 0
        : ((width / 2) / EARTH_RADIUS) * (180 / Math.PI) / cosLat
    r.start = [pos[0] - halfDLng, pos[1] - halfDLat]
    r.current = [pos[0] + halfDLng, pos[1] + halfDLat]
    delete r.position
    delete r.width
    delete r.height
    row.updatedAt = new Date()
  })
}

