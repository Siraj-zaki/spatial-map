/**
 * A storage bin = one *addressable location* the user can attach inventory
 * metadata to. Originally a bin was strictly a grid cell (v5/v6 schema,
 * keyed by `[gridId+row+col+level]`). From v7 onwards a bin can also be a
 * whole non-grid shape (polygon / circle / line / marker / image) — the
 * caller picks via `targetKind` and supplies either the grid-cell address
 * or the shape's `id`. This generalisation is what makes the Data-Link
 * Layer work uniformly across shape kinds.
 *
 * When a grid is deleted the caller is responsible for cascading the
 * delete (see `handleDeleteGridById` in `routes/create-grids.tsx`); when
 * a non-grid shape is deleted call `deleteBinForShape()`.
 */
export type BinStatus = 'empty' | 'occupied' | 'reserved'

/** What the bin row points at. v7+. Legacy rows are backfilled to 'grid-cell'. */
export type BindingKind = 'grid-cell' | 'polygon' | 'circle' | 'line' | 'marker' | 'image' | 'model'

export interface Bin {
  id?: number
  /**
   * v7+. Discriminates between a grid-cell binding (keyed by
   * `[gridId+row+col+level]`) and a whole-shape binding (keyed by
   * `[targetKind+shapeId]`). Legacy rows are backfilled to 'grid-cell'.
   */
  targetKind: BindingKind
  /** Required when `targetKind === 'grid-cell'`; undefined otherwise. */
  gridId?: number
  row?: number
  col?: number
  /**
   * Vertical level inside the rack. 0 = ground (default for single-level
   * grids and for any legacy bin row that predates the v6 schema). Higher
   * values stack upward; the renderer computes each level's altitude as
   * `gridElevation + level * levelHeight`. Grid-cell bindings only.
   */
  level?: number
  /** Required when `targetKind !== 'grid-cell'`; undefined for grid cells. */
  shapeId?: number
  /**
   * Status drives the bin-status tint overlay. Required for grid-cell
   * bindings (defaults to 'empty' on create); optional for non-grid
   * bindings where the user may not need a tri-state model.
   */
  status?: BinStatus
  /** Optional SKU / item identifier stored in this bin. */
  sku?: string
  /** Optional capacity (units, kg, pallets — whatever the user tracks). */
  capacity?: number
  notes?: string
  /**
   * v7+. Free-form external identifier — e.g. a WMS bin code, GS1 GLN
   * extension, or barcode payload. Indexed so an import pipeline can do
   * fast "does this code already exist?" lookups.
   */
  externalCode?: string
  /**
   * v7+. Open key/value bag for WMS-supplied attributes that don't fit
   * the built-in columns (weight, lot, expiry, owner, …). The set of
   * keys allowed here is described by the `attributeDefinitions` table
   * so the editor and tooltip can render fields uniformly.
   */
  customProperties?: Record<string, unknown>
  /** v7+. Timestamp of the last successful import / sync that touched this bin. */
  lastSyncedAt?: Date
  /** v7+. FK to `dataSources.id` — which source last wrote this bin. */
  syncSource?: number
  /**
   * v13+. Optional floor-plan reference mirroring the stamp on the
   * bound shape. Hidden when the referenced image is hidden.
   */
  floorPlanId?: number
  updatedAt: Date
}

