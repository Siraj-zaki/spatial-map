/**
 * v22+. Phase 8 — cross-stream correlation rules.
 *
 * A `CorrelationRule` is "when X happens, do Y" — the first piece of
 * business logic the data plane runs on its own state. Triggers are
 * matched against incoming events (CV detections, sensor readings,
 * RFID reads); actions mutate state-table entities (shipment state,
 * bin status) and write an audit row per fire.
 *
 * Two trigger families ship in Phase 8a:
 *
 *   - `cv-detection` — fires when a CV detection lands on a shape,
 *     optionally filtered by objectClass and a rolling minCount over
 *     the last `windowMs` of detections.
 *   - `sensor-reading` — fires when a sensor reading crosses a
 *     threshold (`>`, `<`, `>=`, `<=`).
 *
 * Two actions ship:
 *
 *   - `advance-shipment-state` — finds shipments with `state ∈ from`
 *     and the matching `doorId`/`zoneId`, transitions each to `to`.
 *   - `set-bin-status` — sets a bin's status (looked up by
 *     externalCode or directly by id).
 *
 * `cooldownMs` debounces a noisy trigger so a rule doesn't flap five
 * times a second. `lastFiredAt + cooldownMs` must be in the past
 * before the rule fires again.
 */
export type CorrelationTrigger =
  | {
      kind: 'cv-detection'
      /** Optional class filter — when set, only detections of this class count. */
      objectClass?: string
      /** Minimum cumulative count within the trigger's window to fire. Default 1. */
      minCount?: number
      /** Bound shape that detections must target. */
      targetShapeKind?: BindingKind
      targetShapeId?: number
      /** Rolling window in ms over which `minCount` is summed. Default 10s. */
      windowMs?: number
    }
  | {
      kind: 'sensor-reading'
      /** Optional sensorId filter. When unset, the rule applies to every sensor. */
      sensorId?: string
      op: '>' | '<' | '>=' | '<='
      threshold: number
    }
  | {
      /**
       * Phase 8b — RFID tag enters a bound polygon. The engine runs a
       * point-in-polygon test against the read's lng/lat. Optional
       * `tagIdPattern` matches a substring (e.g. "PALLET-" prefix).
       */
      kind: 'rfid-read'
      polygonId: number
      tagIdPattern?: string
    }
  | {
      /**
       * Phase 8c — asset geofence. Fires when an asset transitions
       * between "outside" and "inside" the bound polygon. The engine
       * keeps per-asset inside-state in memory across ticks so we only
       * fire on the *transition*, not on every position update while
       * the asset stays inside.
       */
      kind: 'asset-position'
      polygonId: number
      /** 'enter' fires on outside→inside; 'leave' fires on inside→outside. */
      direction: 'enter' | 'leave'
      assetIdPattern?: string
    }
  | {
      /**
       * Phase 8c — fires when a shipment's state transitions into one
       * of `toStates`. Used for cascade rules ("when any shipment
       * reaches `loading`, emit an alert + push a webhook").
       */
      kind: 'shipment-state-change'
      toStates: ShipmentState[]
      doorId?: number
    }

export type CorrelationAction =
  | {
      kind: 'advance-shipment-state'
      to: ShipmentState
      /** Allowed prior states. Empty array means "any forward-compatible state". */
      from?: ShipmentState[]
      /** Optional door / zone match: shipments whose `doorId` equals this. */
      doorId?: number
    }
  | {
      kind: 'set-bin-status'
      status: BinStatus
      /** Bin lookup by externalCode (the same key the data-link importer uses). */
      binExternalCode?: string
      /** Or directly by Bin.id. Mutually exclusive with `binExternalCode`. */
      binId?: number
    }
  | {
      /**
       * Phase 8b — emit a system alert. The engine writes a row into
       * `alerts`; the editor's floating panel renders unacknowledged
       * ones. Template tokens in `messageTemplate` (`{tagId}`,
       * `{value}`, `{shapeId}`) are substituted from the firing event.
       */
      kind: 'emit-alert'
      level: 'info' | 'warn' | 'critical'
      messageTemplate: string
    }
  | {
      /**
       * Phase 8c — forward a synthetic patch through a configured
       * outbound-capable Stream. Reuses `pushOutboundPatch`, so the
       * audit log captures every fire with `before/after`.
       *
       * The patch is `{ trigger: <ruleName>, ctx: <FireContext> }` —
       * enough for a downstream system to know what happened without
       * the engine knowing which destination it's calling.
       */
      kind: 'call-outbound'
      /** Stream id whose endpoint owns the destination URL + auth. */
      streamId: number
      method?: 'POST' | 'PATCH' | 'PUT'
    }
  | {
      /**
       * Phase 8c — one-shot POST to a configured webhook (Slack /
       * PagerDuty / generic). `bodyTemplate` is the JSON payload
       * with `{token}` substitution from the firing context. Headers
       * are caller-supplied — usually `{ "Content-Type":
       * "application/json" }`.
       */
      kind: 'notify-webhook'
      url: string
      bodyTemplate: string
      headers?: Record<string, string>
    }
  | {
      /**
       * Phase 8c — set the `description` (used as a status banner) on
       * a zone row. Cheap symbolic action useful as a smoke-test for
       * the rule pipeline.
       */
      kind: 'set-zone-status'
      zoneId: number
      status: string
    }

export interface CorrelationRule {
  id?: number
  name: string
  enabled: boolean
  trigger: CorrelationTrigger
  action: CorrelationAction
  /** Minimum gap between fires, in ms. Defaults to 5s. */
  cooldownMs?: number
  /** Last successful fire — used by the cooldown check. */
  lastFiredAt?: Date
  /** Lifetime fire count for the rule, for the UI list. */
  fireCount: number
  /** Phase 7d — owning tenant. */
  tenantId?: number
  createdAt: Date
  updatedAt: Date
}

