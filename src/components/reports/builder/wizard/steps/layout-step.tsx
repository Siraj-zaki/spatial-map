/**
 * Layout step — Superset-style freeform grid canvas + right-side
 * palette. Widgets live on a 12-col CSS grid; users drag them
 * around, resize by the bottom-right corner, or drag types from the
 * palette to spawn new widgets at the drop position.
 *
 * Primary widgets (auto-generated by the report-type recipe) are
 * treated like normal widgets on the canvas — the user can freely
 * move/resize them and the positions survive re-saves via
 * `layout.widgetPositions` overrides. They can't be deleted (they'd
 * regenerate) but they can be hidden.
 */
export function LayoutStep() {
  const { t } = useTranslation()
  const { draft, update } = useWizard()

  // Live-preview the exact widget list the viewer will render. All
  // canvas positioning applies on top of these positions.
  const preview = useMemo(() => toV2Spec(draft), [draft])
  const layout = useMemo(() => draft.layout ?? ({ kind: 'document' } as LayoutConfig), [draft.layout])
  const patchLayout = useCallback(
    (patch: Partial<LayoutConfig>) => update({ layout: { ...layout, ...patch } }),
    [layout, update],
  )

  const hidden = useMemo(() => new Set(draft.hiddenWidgetIds), [draft.hiddenWidgetIds])
  const positioned = useMemo(
    () => withAutoPositions((preview.widgets ?? []).filter((w) => !hidden.has(w.id))),
    [preview.widgets, hidden],
  )
  const paletteExisting = useMemo(
    () => draft.extraWidgets.filter((w) => hidden.has(w.id)),
    [draft.extraWidgets, hidden],
  )

  // ─── mutations ────────────────────────────────────────────────
  const setPosition = useCallback(
    (id: string, position: WidgetPosition) => {
      patchLayout({
        widgetPositions: {
          ...(layout.widgetPositions ?? {}),
          [id]: position,
        },
      })
    },
    [layout.widgetPositions, patchLayout],
  )

  const hideExtra = useCallback(
    (id: string) => {
      if (hidden.has(id)) return
      update({ hiddenWidgetIds: [...draft.hiddenWidgetIds, id] })
    },
    [hidden, draft.hiddenWidgetIds, update],
  )
  const showExtra = useCallback(
    (id: string) => {
      update({ hiddenWidgetIds: draft.hiddenWidgetIds.filter((x) => x !== id) })
    },
    [draft.hiddenWidgetIds, update],
  )
  const deleteExtra = useCallback(
    (id: string) => {
      update({
        extraWidgets: draft.extraWidgets.filter((w) => w.id !== id),
        hiddenWidgetIds: draft.hiddenWidgetIds.filter((x) => x !== id),
      })
    },
    [draft.extraWidgets, draft.hiddenWidgetIds, update],
  )

  const addNewWidget = useCallback(
    (kind: WidgetKindV2, dropPos: { x: number; y: number }) => {
      const size = defaultSizeFor(kind)
      const position: WidgetPosition = {
        x: Math.max(0, Math.min(GRID_COLS - size.w, dropPos.x)),
        y: Math.max(0, dropPos.y),
        w: size.w,
        h: size.h,
      }
      const id = `w_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`
      const widget: ReportWidgetV2 = {
        id,
        kind,
        title: undefined,
        position,
        order: 20 + draft.extraWidgets.length,
        bindings: {},
      }
      update({
        extraWidgets: [...draft.extraWidgets, widget],
        layout: {
          ...layout,
          widgetPositions: { ...(layout.widgetPositions ?? {}), [id]: position },
        },
      })
    },
    [draft.extraWidgets, layout, update],
  )

  // Viewer filters compile to params on save, so they count too.
  const paramsCount = draft.params.length + draft.viewerFilters.length

  return (
    <div className="space-y-3">
      {/* Header: intro + mode toggle */}
      <div className="flex flex-wrap items-center gap-2">
        <div className="flex-1 min-w-[280px] rounded-md border border-primary/30 bg-primary/5 px-3 py-2 text-xs flex items-start gap-2">
          <Sparkles className="w-4 h-4 mt-0.5 shrink-0 text-primary" />
          <span className="text-muted-foreground">
            {layout.kind === 'map'
              ? t('reports.wizard.layout.mapHint', {
                  defaultValue: 'The facility map fills the page. Its list floats on the left, the picked record on the right; choose where your other widgets float.',
                })
              : t('reports.wizard.layout.editorHint', {
                  defaultValue:
                    'Drag widget types from the right panel onto the canvas. Drag placed widgets to move them, use the corner handle to resize, and hover for delete + settings.',
                })}
          </span>
        </div>
        <ModeToggle
          value={layout.kind ?? 'document'}
          onChange={(kind) => patchLayout({ kind })}
        />
      </div>

      {layout.kind === 'map' ? (
        <MapLayoutEditor preview={preview} kindIcon={KIND_ICON} />
      ) : (
      <>
      {/* Main split — canvas + sidebar */}
      <div className="grid grid-cols-1 lg:grid-cols-[1fr,280px] gap-3">
        <LayoutCanvas
          widgets={positioned}
          onSetPosition={setPosition}
          onHide={hideExtra}
          onDelete={deleteExtra}
          onExternalDrop={(payload, pos) => {
            if (payload.kind === 'palette-add' && payload.widgetKind) {
              addNewWidget(payload.widgetKind as WidgetKindV2, pos)
            } else if (payload.kind === 'palette-existing' && payload.id) {
              showExtra(payload.id)
              // Also anchor its position at the drop cell.
              const w = draft.extraWidgets.find((x) => x.id === payload.id)
              if (w) {
                const size = hasPosition(w) ? { w: w.position.w, h: w.position.h } : defaultSizeFor(w.kind)
                setPosition(payload.id, {
                  x: Math.max(0, Math.min(GRID_COLS - size.w, pos.x)),
                  y: Math.max(0, pos.y),
                  w: size.w,
                  h: size.h,
                })
              }
            }
          }}
        />

        <Sidebar
          paletteExisting={paletteExisting}
          paramsCount={paramsCount}
          hideParamsBar={Boolean(layout.hideParamsBar)}
          onToggleParams={(show) => patchLayout({ hideParamsBar: !show })}
          onExistingDragStart={() => {}}
        />
      </div>

      <div className="rounded-md border border-border/60 bg-muted/20 px-3 py-2 text-[11px] text-muted-foreground flex items-start gap-2">
        <LayoutTemplate className="w-3.5 h-3.5 mt-0.5 shrink-0" />
        <span>
          {t('reports.wizard.layout.skipHint', {
            defaultValue:
              'No customisation? The viewer falls back to a Grafana/Superset-style flow: filters bar on top, then widgets in the order shown here.',
          })}
        </span>
      </div>
      </>
      )}
    </div>
  )
}

// ─────────────────────────────────────────────── canvas

/** Widget payload for cross-container drag. */
interface CanvasDragPayload {
  kind: 'palette-add' | 'palette-existing' | 'canvas-move'
  widgetKind?: WidgetKindV2 // set when kind === 'palette-add'
  id?: string // set when kind === 'canvas-move' or 'palette-existing'
  /** For canvas-move: the pointer offset inside the widget when the
   *  drag started, so drops land where the user intended not where
   *  they grabbed. Cell units. */
  grabOffsetX?: number
  grabOffsetY?: number
}

const CANVAS_MIME = 'application/x-report-canvas'

function LayoutCanvas({
  widgets,
  onSetPosition,
  onHide,
  onDelete,
  onExternalDrop,
}: {
  widgets: ReportWidgetV2[]
  onSetPosition: (id: string, pos: WidgetPosition) => void
  onHide: (id: string) => void
  onDelete: (id: string) => void
  onExternalDrop: (payload: CanvasDragPayload, cell: { x: number; y: number }) => void
}) {
  const { t } = useTranslation()
  const containerRef = useRef<HTMLDivElement | null>(null)
  const [dropCell, setDropCell] = useState<{ x: number; y: number } | null>(null)

  // Total rows the canvas allocates — enough to fit the tallest widget
  // plus room to drop below.
  const totalRows = useMemo(() => {
    const max = widgets.reduce(
      (acc, w) => Math.max(acc, w.position.y + w.position.h),
      0,
    )
    return Math.max(max + 4, 16)
  }, [widgets])

  const cellFromEvent = (e: React.DragEvent): { x: number; y: number } | null => {
    const el = containerRef.current
    if (!el) return null
    const rect = el.getBoundingClientRect()
    const relX = e.clientX - rect.left
    const relY = e.clientY - rect.top
    const cellW = (rect.width - (GRID_COLS - 1) * GAP_PX) / GRID_COLS
    const x = Math.floor(relX / (cellW + GAP_PX))
    const y = Math.floor(relY / (ROW_HEIGHT_PX + GAP_PX))
    return {
      x: Math.max(0, Math.min(GRID_COLS - 1, x)),
      y: Math.max(0, y),
    }
  }

  const handleDragOver = (e: React.DragEvent) => {
    e.preventDefault()
    e.dataTransfer.dropEffect = 'move'
    const cell = cellFromEvent(e)
    if (cell) setDropCell(cell)
  }

  const handleDrop = (e: React.DragEvent) => {
    e.preventDefault()
    const cell = cellFromEvent(e)
    setDropCell(null)
    if (!cell) return
    const raw = e.dataTransfer.getData(CANVAS_MIME) || e.dataTransfer.getData('text/plain')
    if (!raw) return
    let payload: CanvasDragPayload
    try {
      payload = JSON.parse(raw)
    } catch {
      return
    }
    if (payload.kind === 'canvas-move' && payload.id) {
      const w = widgets.find((x) => x.id === payload.id)
      if (!w) return
      const offX = payload.grabOffsetX ?? 0
      const offY = payload.grabOffsetY ?? 0
      const nextX = Math.max(0, Math.min(GRID_COLS - w.position.w, cell.x - offX))
      const nextY = Math.max(0, cell.y - offY)
      onSetPosition(w.id, { ...w.position, x: nextX, y: nextY })
      return
    }
    onExternalDrop(payload, cell)
  }

  return (
    <div
      ref={containerRef}
      role="grid"
      aria-label={t('reports.wizard.layout.canvasLabel', { defaultValue: 'Layout canvas' })}
      onDragOver={handleDragOver}
      onDrop={handleDrop}
      onDragLeave={() => setDropCell(null)}
      className="relative rounded-md border-2 border-dashed border-border bg-muted/10 p-2 min-h-[400px]"
      style={{
        display: 'grid',
        gridTemplateColumns: `repeat(${GRID_COLS}, 1fr)`,
        gridAutoRows: `${ROW_HEIGHT_PX}px`,
        gap: `${GAP_PX}px`,
      }}
    >
      {/* Background cell outlines so the grid is always visible. */}
      {Array.from({ length: totalRows * GRID_COLS }).map((_, i) => (
        <div
          key={`cell-${i}`}
          className="rounded-sm border border-border/30 bg-background/20 pointer-events-none"
          style={{
            gridColumn: `${(i % GRID_COLS) + 1} / span 1`,
            gridRow: `${Math.floor(i / GRID_COLS) + 1} / span 1`,
          }}
        />
      ))}

      {/* Empty-state hint on top of the empty grid. */}
      {widgets.length === 0 && (
        <div
          className="absolute inset-0 flex flex-col items-center justify-center pointer-events-none text-sm text-muted-foreground"
          aria-hidden
        >
          <LayoutGrid className="w-8 h-8 mb-2 opacity-50" />
          <span>
            {t('reports.wizard.layout.emptyCanvas', {
              defaultValue: 'Drag widgets from the right to build your layout',
            })}
          </span>
        </div>
      )}

      {/* Drop indicator — a highlighted cell showing where a drop
          would land. */}
      {dropCell && (
        <div
          className="rounded border-2 border-primary bg-primary/20 pointer-events-none"
          style={{
            gridColumn: `${dropCell.x + 1} / span 1`,
            gridRow: `${dropCell.y + 1} / span 2`,
          }}
        />
      )}

      {widgets.map((w) => (
        <CanvasWidget
          key={w.id}
          widget={w}
          primary={isPrimaryWidget(w)}
          onDelete={() => onDelete(w.id)}
          onHide={() => onHide(w.id)}
          onResize={(dw, dh) => {
            onSetPosition(w.id, {
              ...w.position,
              w: Math.max(1, Math.min(GRID_COLS - w.position.x, w.position.w + dw)),
              h: Math.max(1, w.position.h + dh),
            })
          }}
        />
      ))}
    </div>
  )
}

/** One placed widget on the canvas. Renders a compact info card
 *  with kind icon + title + hover controls. Draggable via any part
 *  of the card that isn't a button. */
function CanvasWidget({
  widget,
  primary,
  onDelete,
  onHide,
  onResize,
}: {
  widget: ReportWidgetV2
  primary: boolean
  onDelete: () => void
  onHide: () => void
  onResize: (dw: number, dh: number) => void
}) {
  const kindLabel = useWidgetKindLabel()
  const Icon = KIND_ICON[widget.kind] ?? Divide
  const [isDragging, setIsDragging] = useState(false)
  const resizeStart = useRef<{ x: number; y: number } | null>(null)

  const handleDragStart = (e: React.DragEvent) => {
    setIsDragging(true)
    const payload: CanvasDragPayload = {
      kind: 'canvas-move',
      id: widget.id,
      grabOffsetX: 0,
      grabOffsetY: 0,
    }
    const json = JSON.stringify(payload)
    try {
      e.dataTransfer.setData(CANVAS_MIME, json)
    } catch {
      // fall through
    }
    e.dataTransfer.setData('text/plain', json)
    e.dataTransfer.effectAllowed = 'move'
  }

  // Resize: pointer-event based so it doesn't fight HTML5 drag.
  const beginResize = (e: React.PointerEvent) => {
    e.preventDefault()
    e.stopPropagation()
    const target = e.currentTarget as HTMLElement
    target.setPointerCapture(e.pointerId)
    resizeStart.current = { x: e.clientX, y: e.clientY }
  }
  const moveResize = (e: React.PointerEvent) => {
    if (!resizeStart.current) return
    const parent = (e.currentTarget as HTMLElement).parentElement?.parentElement
    if (!parent) return
    const rect = parent.getBoundingClientRect()
    const cellW = (rect.width - (GRID_COLS - 1) * GAP_PX) / GRID_COLS
    const dx = e.clientX - resizeStart.current.x
    const dy = e.clientY - resizeStart.current.y
    // Only commit at cell thresholds.
    const dcw = Math.round(dx / (cellW + GAP_PX))
    const dch = Math.round(dy / (ROW_HEIGHT_PX + GAP_PX))
    if (dcw !== 0 || dch !== 0) {
      resizeStart.current = {
        x: resizeStart.current.x + dcw * (cellW + GAP_PX),
        y: resizeStart.current.y + dch * (ROW_HEIGHT_PX + GAP_PX),
      }
      onResize(dcw, dch)
    }
  }
  const endResize = (e: React.PointerEvent) => {
    const target = e.currentTarget as HTMLElement
    try {
      target.releasePointerCapture(e.pointerId)
    } catch {
      // ignore
    }
    resizeStart.current = null
  }

  return (
    <div
      draggable
      onDragStart={handleDragStart}
      onDragEnd={() => setIsDragging(false)}
      className={cn(
        'group relative rounded-md border bg-card overflow-hidden select-none transition-opacity',
        primary ? 'border-primary/40' : 'border-border',
        isDragging && 'opacity-40',
        'hover:shadow-md hover:border-primary/60',
      )}
      style={{
        gridColumn: `${widget.position.x + 1} / span ${widget.position.w}`,
        gridRow: `${widget.position.y + 1} / span ${widget.position.h}`,
        cursor: 'move',
      }}
    >
      {/* Body */}
      <div className="p-2 h-full flex flex-col gap-1">
        <div className="flex items-center gap-1.5">
          <Icon className="w-3.5 h-3.5 text-primary shrink-0" aria-hidden />
          <span className="text-[10px] uppercase tracking-wider text-muted-foreground truncate">
            {kindLabel(widget.kind)}
          </span>
          {primary && (
            <span
              title="Auto-generated"
              className="text-[9px] uppercase tracking-wider px-1 py-0.5 rounded bg-primary/10 text-primary shrink-0"
            >
              auto
            </span>
          )}
          <div className="flex-1" />
        </div>
        <div className="text-xs font-medium truncate">
          {widget.title ?? (primary ? 'Auto-generated' : '(untitled)')}
        </div>
      </div>

      {/* Hover controls */}
      <div className="absolute top-1 right-1 flex items-center gap-0.5 opacity-0 group-hover:opacity-100 transition-opacity">
        <button
          type="button"
          onClick={(e) => {
            e.stopPropagation()
            // Settings — jumps back to Widgets step. Not wired here;
            // hover shown as future-affordance.
          }}
          className="w-6 h-6 rounded flex items-center justify-center bg-background/80 hover:bg-accent text-muted-foreground"
          aria-label="Settings"
        >
          <Settings2 className="w-3 h-3" />
        </button>
        {primary ? (
          // Primaries can't be deleted (they'd regenerate); hide instead.
          <button
            type="button"
            onClick={(e) => {
              e.stopPropagation()
              onHide()
            }}
            className="w-6 h-6 rounded flex items-center justify-center bg-background/80 hover:bg-accent text-muted-foreground"
            aria-label="Hide"
          >
            <Lock className="w-3 h-3" />
          </button>
        ) : (
          <>
            <button
              type="button"
              onClick={(e) => {
                e.stopPropagation()
                onHide()
              }}
              className="w-6 h-6 rounded flex items-center justify-center bg-background/80 hover:bg-accent text-muted-foreground"
              aria-label="Hide"
            >
              <ChevronDown className="w-3 h-3" />
            </button>
            <button
              type="button"
              onClick={(e) => {
                e.stopPropagation()
                onDelete()
              }}
              className="w-6 h-6 rounded flex items-center justify-center bg-background/80 hover:bg-destructive/10 text-destructive"
              aria-label="Delete"
            >
              <Trash2 className="w-3 h-3" />
            </button>
          </>
        )}
      </div>

      {/* Resize handle — bottom-right corner. Pointer events so it
          doesn't conflict with the widget-level HTML5 drag. */}
      <div
        onPointerDown={beginResize}
        onPointerMove={moveResize}
        onPointerUp={endResize}
        onPointerCancel={endResize}
        className="absolute bottom-0 right-0 w-3 h-3 cursor-nwse-resize opacity-0 group-hover:opacity-100 transition-opacity"
        aria-label="Resize"
      >
        <div className="absolute bottom-0.5 right-0.5 w-2 h-2 border-r-2 border-b-2 border-primary rounded-sm" />
      </div>
    </div>
  )
}

// ─────────────────────────────────────────────── sidebar

function Sidebar({
  paletteExisting,
  paramsCount,
  hideParamsBar,
  onToggleParams,
  onExistingDragStart,
}: {
  paletteExisting: ReportWidgetV2[]
  paramsCount: number
  hideParamsBar: boolean
  onToggleParams: (show: boolean) => void
  onExistingDragStart: () => void
}) {
  const { t } = useTranslation()
  return (
    <aside className="rounded-md border border-border bg-card overflow-hidden lg:sticky lg:top-4 lg:self-start">
      <div className="px-3 py-2 border-b border-border text-[10px] uppercase tracking-wider text-muted-foreground font-medium">
        {t('reports.wizard.layout.insert', { defaultValue: 'Insert' })}
      </div>

      <div className="p-3 space-y-4 max-h-[600px] overflow-y-auto">
        {/* Filters bar toggle */}
        <SidebarSection
          title={t('reports.wizard.layout.filtersBar', { defaultValue: 'Filters bar' })}
        >
          {paramsCount === 0 ? (
            <div className="text-[10px] text-muted-foreground italic">
              {t('reports.wizard.layout.filtersBarNone', {
                defaultValue: 'No parameters declared yet.',
              })}
            </div>
          ) : (
            <label className="flex items-center gap-2 text-xs cursor-pointer">
              <input
                type="checkbox"
                checked={!hideParamsBar}
                onChange={(e) => onToggleParams(e.target.checked)}
                className="w-3.5 h-3.5"
              />
              <FilterIcon className="w-3.5 h-3.5 text-primary" />
              <span className="flex-1 truncate">
                {t('reports.wizard.layout.showFiltersBar', {
                  count: paramsCount,
                  defaultValue: 'Show {{count}} filters above report',
                })}
              </span>
            </label>
          )}
        </SidebarSection>

        {/* Existing / unplaced widgets */}
        <SidebarSection
          title={t('reports.wizard.layout.existing', {
            count: paletteExisting.length,
            defaultValue: 'Hidden widgets ({{count}})',
          })}
        >
          {paletteExisting.length === 0 && (
            <div className="text-[10px] text-muted-foreground italic">
              {t('reports.wizard.layout.existingEmpty', {
                defaultValue: 'Hidden widgets appear here — drag them back to the canvas to show them.',
              })}
            </div>
          )}
          <ul className="space-y-1">
            {paletteExisting.map((w) => (
              <li key={w.id}>
                <PaletteExistingChip
                  widget={w}
                  onDragStart={onExistingDragStart}
                />
              </li>
            ))}
          </ul>
        </SidebarSection>

        {/* Add widget — palette of insertable kinds */}
        {PALETTE_GROUPS.map((group) => (
          <SidebarSection key={group.title} title={group.title}>
            <div className="grid grid-cols-2 gap-1.5">
              {group.kinds.map((k) => (
                <PaletteAddChip key={k} kind={k} />
              ))}
            </div>
          </SidebarSection>
        ))}
      </div>
    </aside>
  )
}

function SidebarSection({
  title,
  children,
}: {
  title: string
  children: React.ReactNode
}) {
  const [open, setOpen] = useState(true)
  return (
    <div className="space-y-1.5">
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        className="w-full flex items-center gap-1 text-[10px] uppercase tracking-wider font-medium text-muted-foreground hover:text-foreground"
      >
        {open ? (
          <ChevronDown className="w-3 h-3" />
        ) : (
          <ChevronUp className="w-3 h-3 rotate-180" />
        )}
        <span>{title}</span>
      </button>
      {open && <div className="ps-1">{children}</div>}
    </div>
  )
}

function PaletteAddChip({ kind }: { kind: WidgetKindV2 }) {
  const kindLabel = useWidgetKindLabel()
  const Icon = KIND_ICON[kind] ?? Divide
  const handleDragStart = (e: React.DragEvent) => {
    const payload: CanvasDragPayload = { kind: 'palette-add', widgetKind: kind }
    const json = JSON.stringify(payload)
    try {
      e.dataTransfer.setData(CANVAS_MIME, json)
    } catch {
      // fall through
    }
    e.dataTransfer.setData('text/plain', json)
    // Also emit the shared drag mime so other listeners keep working.
    setDragPayload(e.dataTransfer, {
      source: 'palette',
      kind: 'widget',
      id: `palette-${kind}`,
    })
    e.dataTransfer.effectAllowed = 'copy'
  }
  return (
    <div
      draggable
      onDragStart={handleDragStart}
      className="flex flex-col items-center gap-1 rounded-md border border-border bg-background px-2 py-2 text-[10px] cursor-grab active:cursor-grabbing hover:bg-accent hover:border-primary/40 transition-colors"
      title={kindLabel(kind)}
    >
      <Icon className="w-4 h-4 text-primary" />
      <span className="max-w-full truncate">{kindLabel(kind)}</span>
    </div>
  )
}

function PaletteExistingChip({
  widget,
  onDragStart,
}: {
  widget: ReportWidgetV2
  onDragStart: () => void
}) {
  const kindLabel = useWidgetKindLabel()
  const Icon = KIND_ICON[widget.kind] ?? Divide
  const handle = (e: React.DragEvent) => {
    const payload: CanvasDragPayload = {
      kind: 'palette-existing',
      id: widget.id,
    }
    const json = JSON.stringify(payload)
    try {
      e.dataTransfer.setData(CANVAS_MIME, json)
    } catch {
      // fall through
    }
    e.dataTransfer.setData('text/plain', json)
    setDragPayload(e.dataTransfer, {
      source: 'palette',
      kind: 'widget',
      id: widget.id,
    })
    e.dataTransfer.effectAllowed = 'move'
    onDragStart()
  }
  return (
    <div
      draggable
      onDragStart={handle}
      className="flex items-center gap-2 rounded-md border border-border bg-background px-2 py-1.5 text-xs cursor-grab active:cursor-grabbing hover:bg-accent transition-colors"
    >
      <GripVertical className="w-3 h-3 text-muted-foreground shrink-0" aria-hidden />
      <Icon className="w-3.5 h-3.5 text-primary shrink-0" />
      <div className="flex-1 min-w-0">
        <div className="truncate">{widget.title || kindLabel(widget.kind)}</div>
        <div className="text-[9px] uppercase tracking-wider text-muted-foreground">
          {kindLabel(widget.kind)}
        </div>
      </div>
    </div>
  )
}

