function ModeToggle({
  value,
  onChange,
}: {
  value: 'document' | 'grid' | 'map'
  onChange: (v: 'document' | 'grid' | 'map') => void
}) {
  const { t } = useTranslation()
  const modes: Array<{ id: 'document' | 'grid' | 'map'; label: string; icon?: typeof MapIcon }> = [
    { id: 'document', label: t('reports.wizard.layout.modeDocument', { defaultValue: 'Document' }) },
    { id: 'grid', label: t('reports.wizard.layout.modeGrid', { defaultValue: 'Grid' }) },
    { id: 'map', label: t('reports.wizard.layout.modeMap', { defaultValue: 'Full map' }), icon: MapIcon },
  ]
  return (
    <div className="inline-flex rounded-md border border-border overflow-hidden shrink-0" role="radiogroup" aria-label={t('reports.wizard.layout.mode', { defaultValue: 'Layout' })}>
      {modes.map((m) => {
        const Icon = m.icon
        return (
          <button
            key={m.id}
            type="button"
            role="radio"
            aria-checked={value === m.id}
            onClick={() => onChange(m.id)}
            className={cn(
              'inline-flex items-center gap-1.5 px-3 py-1 text-xs transition-colors border-e border-border last:border-e-0',
              value === m.id ? 'bg-primary text-primary-foreground' : 'bg-background text-muted-foreground hover:bg-accent',
            )}
          >
            {Icon && <Icon className="h-3.5 w-3.5" aria-hidden />}
            {m.label}
          </button>
        )
      })}
    </div>
  )
}

